const assert=require('node:assert/strict');
const tracking=require('../maintenance-tracking.js');
const anchor={km:125000,at:'2026-09-01T12:00:00+03:00'};
const end='2026-09-03T12:00:00+03:00';
const segments=[{start:anchor.at,end:'2026-09-02T12:00:00+03:00',km:120,complete:true},{start:'2026-09-02T12:00:00+03:00',end,km:180,complete:true}];
assert.equal(tracking.mileageFromAnchor(anchor,segments,end).km,125300);
assert.deepEqual(tracking.mileageFromAnchor(anchor,segments,end),tracking.mileageFromAnchor(anchor,segments,end));
assert.equal(tracking.mileageFromAnchor(anchor,[segments[0],segments[0]],end).status,'incomplete');
assert.equal(tracking.mileageFromAnchor(anchor,[segments[1]],end).km,null);
assert.equal(tracking.mileageFromAnchor(anchor,[{...segments[0],complete:false}],end).km,null);
assert.equal(tracking.mileageFromAnchor({...anchor,at:'2026-09-01'},segments,end).status,'invalid');
const oil={serviceKm:120000,currentKm:129000,intervalKm:10000,serviceAt:anchor.at,asOf:end};
assert.equal(tracking.maintenanceStatus(oil).remainingKm,1000);
assert.equal(tracking.maintenanceStatus({...oil,currentKm:130000}).status,'due');
assert.equal(tracking.maintenanceStatus({...oil,currentKm:110000}).status,'unknown');
assert.equal(tracking.maintenanceStatus({...oil,intervalDays:1}).status,'due');
assert.equal(tracking.maintenanceStatus({...oil,intervalDays:30,currentKm:null}).status,'unknown');
assert.equal(tracking.maintenanceStatus({...oil,intervalKm:40000}).remainingKm,31000);
const fuel={anchorLiters:80,capacityLiters:100,addedLiters:20,distanceKm:300,litersPer100Km:10,completeData:true};
assert.equal(tracking.estimateFuel(fuel).rangeKm,700);
assert.equal(tracking.estimateFuel({...fuel,completeData:false}).status,'unknown');
assert.equal(tracking.estimateFuel({...fuel,addedLiters:200}).status,'needs-reconciliation');
console.log('Maintenance anchor replay, GPS gaps/duplicates, independent intervals and fuel estimate uncertainty PASS');
